    "import json\n",
    "import os\n",
    "\n",
    "class BankSystem:\n",
    "    def __init__(self, data_file=\"accounts.json\"):\n",
    "        self.data_file = data_file\n",
    "        self.accounts = self.load_data()\n",
    "\n",
    "    def load_data(self):\n",
    "        # Load account data from a JSON file if it exists, otherwise start fresh\n",
    "        if os.path.exists(self.data_file):\n",
    "            with open(self.data_file, 'r') as file:\n",
    "                try:\n",
    "                    return json.load(file)\n",
    "                except json.JSONDecodeError:\n",
    "                    return {}\n",
    "        return {}\n",
    "\n",
    "    def save_data(self):\n",
    "        # Commit all account states back to our JSON database file\n",
    "        with open(self.data_file, 'w') as file:\n",
    "            json.dump(self.accounts, file, indent=4)\n",
    "\n",
    "    def create_account(self, name, pin, initial_deposit):\n",
    "        # Automatically generate a unique 5-digit account number\n",
    "        import random\n",
    "        while True:\n",
    "            acc_num = str(random.randint(10000, 99999))\n",
    "            if acc_num not in self.accounts:\n",
    "                break\n",
    "        \n",
    "        # Save user fields including a transaction log history array\n",
    "        self.accounts[acc_num] = {\n",
    "            \"name\": name,\n",
    "            \"pin\": pin,\n",
    "            \"balance\": float(initial_deposit),\n",
    "            \"history\": [f\"Account opened with initial deposit of ${initial_deposit}\"]\n",
    "        }\n",
    "        self.save_data()\n",
    "        print(f\"\\n[SUCCESS] Account created successfully for {name}!\")\n",
    "        print(f\"-> Your Account Number is: {acc_num} (Keep this safe!)\")\n",
    "        return acc_num\n",
    "\n",
    "    def authenticate(self, acc_num, pin):\n",
    "        # Validates login data entry matches records\n",
    "        if acc_num in self.accounts and self.accounts[acc_num][\"pin\"] == pin:\n",
    "            return True\n",
    "        return False\n",
    "\n",
    "    def deposit(self, acc_num, amount):\n",
    "        if amount <= 0:\n",
    "            print(\"[ERROR] Deposit amount must be positive.\")\n",
    "            return\n",
    "        self.accounts[acc_num][\"balance\"] += amount\n",
    "        self.accounts[acc_num][\"history\"].append(f\"Deposited: ${amount}\")\n",
    "        self.save_data()\n",
    "        print(f\"[SUCCESS] ${amount} deposited. New balance: ${self.accounts[acc_num]['balance']}\")\n",
    "\n",
    "    def withdraw(self, acc_num, amount):\n",
    "        if amount <= 0:\n",
    "            print(\"[ERROR] Withdrawal amount must be positive.\")\n",
    "            return\n",
    "        if self.accounts[acc_num][\"balance\"] < amount:\n",
    "            print(f\"[ERROR] Insufficient funds! Your balance is ${self.accounts[acc_num]['balance']}\")\n",
    "            return\n",
    "        self.accounts[acc_num][\"balance\"] -= amount\n",
    "        self.accounts[acc_num][\"history\"].append(f\"Withdrew: ${amount}\")\n",
    "        self.save_data()\n",
    "        print(f\"[SUCCESS] ${amount} withdrawn. New balance: ${self.accounts[acc_num]['balance']}\")\n",
    "\n",
    "    def check_balance(self, acc_num):\n",
    "        print(f\"Current Account Balance: ${self.accounts[acc_num]['balance']}\")\n",
    "\n",
    "    def view_history(self, acc_num):\n",
    "        print(\"\\n--- Transaction History ---\")\n",
    "        for log in self.accounts[acc_num][\"history\"]:\n",
    "            print(f\"- {log}\")\n",
    "        print(\"---------------------------\")\n"
